// 오늘의 팁 (하루 동안 동일). childId를 섞으면 아이별로 조금씩 달라짐.
export function tipOfToday(seed = 0): Tip {
  const d = new Date();
  const dayOfYear = Math.floor(
    (d.getTime() - new Date(d.getFullYear(), 0, 0).getTime()) / 86400000
  );
  const idx = (dayOfYear + seed) % TIPS.length;
  return TIPS[idx];
}
